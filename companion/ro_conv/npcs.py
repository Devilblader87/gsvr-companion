"""RO classic NPC sprite packs (w43 npc lane, docs/design/ro_npc_world.md): one pack per town group, 'npc_<town>' = ONE RPG1 container with RSAT + RSAN (no map),
the sprites 'npc_<id>' of every decor NPC of the group's maps (Editor/ro_npc_world.txt; the id lists are generated into npcsets.py by tools/ro_npc_world_gen.py).

Sprite id -> client file: read from the OWNER's client at build time (nothing of the game in git): npcidentity.lub (jobtbl.JT_<NAME> = id) + jobname.lub
(JobNameTable[jobtbl.JT_<NAME>] = file name) -> data/sprite/npc/<file>.spr/.act; api.NPC_SPRITES (the ids looked up once for the w34 / w41 lanes) is the fallback for a client
whose lub tables lack an id. Idle only, 8 directions (a one-direction NPC shows its pose from every side), scaled like the player (ref height = the Novice of the same client, the
world uses one pxM for every set). A missing sprite is ONE grouped warning line; the world draws a placeholder for it. Pack size budget: NPC_MAX_BYTES (the build fails above it,
so a broken client cannot hand the world a giant string load)."""
import os
import struct
import sys

from . import sprite, lub, items, npcsets, maps2_data
from .grf import Vfs, GrfError

_ROSE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'rose_conv')
if _ROSE not in sys.path:
    sys.path.append(_ROSE)
import rpg1 as P            # noqa: E402

# w46 maps2: the NPC groups of the second map wave (companion/ro_conv/maps2_data.py, generated by tools/ro_maps2_gen.py) come after the w43 groups
NPC_PACKS = dict((g, {'kind': 'npc', 'label': 'NPCs ' + g[4:]}) for g in list(npcsets.NPC_GROUPS) + list(maps2_data.NPC_GROUPS))
NPC_ORDER = tuple(npcsets.NPC_GROUPS) + tuple(maps2_data.NPC_GROUPS)
NPC_REV = 1
NPC_MAX_BYTES = 24 * 1024 * 1024
NPC_MAX_SIDE = 160                     # a few NPC sprites (ships, statues) are huge: composed again at 1 / 2^n above this side (sprite.FF_SHIFT), like the monsters
NPC_PATH = 'data/sprite/npc/%s'


def group_of(m):
    """the npc pack of map `m`, '' when none"""
    for g, ms in list(npcsets.NPC_GROUPS.items()) + list(maps2_data.NPC_GROUPS.items()):
        if m in ms:
            return g
    return ''


def id_files(vfs):
    """{sprite id: client file name (lower case)} from the client's npcidentity.lub + jobname.lub; {} when the client has neither (the fallback table then applies)."""
    try:
        ident = lub.parse(items._read_first(vfs, 'npcidentity.lub'))
        names = lub.parse(items._read_first(vfs, 'jobname.lub'))
    except (KeyError, lub.LubError, ValueError, IndexError, struct.error):
        return {}
    jt = dict((k, v) for s, k, v in ident if s == 'jobtbl' and isinstance(k, str) and isinstance(v, int))
    out = {}
    for s, k, v in names:
        if s == 'JobNameTable' and isinstance(k, tuple) and len(k) == 3 and k[0] == 'gt' and isinstance(v, str) and k[2] in jt:
            out.setdefault(jt[k[2]], v.lower())
    return out


def npc_set(vfs, ids, warn=None):
    """-> [sprite dict 'npc_<id>'] for the ids the client has (sorted ids)."""
    from . import api
    table = id_files(vfs)
    out, miss = [], []
    _E = (sprite.FormatError, ValueError, IndexError, struct.error)
    for sid in sorted(set(ids)):
        fn = table.get(sid) or api.NPC_SPRITES.get(sid)
        if not fn:
            miss.append(sid)
            continue
        base = NPC_PATH % fn
        if sid >= 1000 and not vfs.exists(base + '.spr'):          # a monster job id used as an NPC look (Alice, Orc Lady ...): the client file is a monster sprite
            base = api.PATH_MONSTER + fn
        try:
            sp = sprite.convert_sprite('npc_%d' % sid, sprite.KIND_MONSTER, vfs.read(base + '.spr'), vfs.read(base + '.act'), anims=(sprite.ANIM_IDLE,), still_anims=(sprite.ANIM_IDLE,), max_side=NPC_MAX_SIDE)
        except KeyError:
            miss.append(sid)
            continue
        except _E as e:
            if warn is not None:
                warn.append('sprites: npc %d: %s' % (sid, e))
            continue
        for d in range(1, 8):
            if not sp['clips'][d]['frames']:
                sp['clips'][d] = sp['clips'][0]
        out.append(sp)
    if miss and warn is not None:
        warn.append('sprites: %d npc sprites not in the client data (placeholders in the world): %s' % (len(miss), ', '.join(str(s) for s in miss[:12]) + (' ...' if len(miss) > 12 else '')))
    return out


def sections(vfs, name, warn=None):
    """-> [(tag, version, count, data)] RSAT + RSAN of the group `name`; [] when none of its sprites is in the client."""
    from . import api
    sp = npc_set(vfs, npcsets.NPC_SET_IDS.get(name) or maps2_data.NPC_SET_IDS.get(name, ()), warn)
    if not sp:
        return []
    refh = None
    try:
        body, head = api._pair(vfs, api.SPRITE_SEX)
        refh = sprite.ref_height_px(body, head)
    except (KeyError, sprite.FormatError, ValueError, IndexError, struct.error):
        pass
    rsat, rsan = sprite.build_set(sp, ref=(None, None), ref_px=refh if refh else 0.0)
    return [(sprite.TAG_RSAT, 1, 1, rsat), (sprite.TAG_RSAN, sprite.RSAN_VERSION, len(sp), rsan)]


def build(name, folder, out_path, progress=None, cancel=None, log=None):
    """the 'npc_<town>' pack -> out_path. -> dict(name, bytes, sprites, warnings)."""
    from .api import check_install, BuildError, Cancelled
    if name not in NPC_PACKS:
        raise BuildError('not an npc pack: %r' % name)
    ok, why = check_install(folder)
    if not ok:
        raise BuildError('Ragnarok folder not usable: %s' % why)

    def tick(stage, f):
        if cancel is not None and cancel():
            raise Cancelled(name)
        if progress is not None:
            progress(stage, f)
    tick('grf', 0.0)
    try:
        vfs = Vfs(folder)
    except GrfError as e:
        raise BuildError(str(e).replace(folder, '<folder>'))
    warns = list(vfs.errors)
    tick('sprites', 0.1)
    try:
        secs = sections(vfs, name, warns)
    except sprite.FormatError as e:
        raise BuildError('npc sprites: %s' % e)
    if not secs:
        raise BuildError('no npc sprites of %s in the client data' % name)
    data = P.write_pack(secs)
    if len(data) > NPC_MAX_BYTES:
        raise BuildError('npc pack %s too large (%d > %d bytes)' % (name, len(data), NPC_MAX_BYTES))
    tick('write', 0.9)
    part = out_path + '.part'
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    try:
        with open(part, 'wb') as f:
            f.write(data)
        os.replace(part, out_path)
    finally:
        if os.path.exists(part):
            os.remove(part)
    if log is not None:
        log('npc: %s %d sprites, %d bytes' % (name, secs[1][2], len(data)))
    tick('write', 1.0)
    return {'name': name, 'bytes': len(data), 'sprites': secs[1][2], 'warnings': warns[:40]}
